#!/usr/bin/env python3
from __future__ import annotations

import argparse
import asyncio
import json
import threading
from pathlib import Path
from typing import Any, Dict

from protocol_mapping import DEFAULT_PORTS, PROTOCOLS, MappingError


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run one protocol simulator on Windows for tb-gateway.")
    parser.add_argument(
        "--protocol",
        required=True,
        choices=list(PROTOCOLS),
        help="protocol simulator to run; one protocol per process",
    )
    parser.add_argument(
        "--mapping",
        required=True,
        help="connector-mapping-<protocol>.json generated by generate_gateway_config.py",
    )
    parser.add_argument("--host", default="0.0.0.0", help="listen host")
    parser.add_argument("--port", type=int, default=None, help="listen port")
    return parser.parse_args()


def load_mapping(path: str, protocol: str) -> Dict[str, Any]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if data.get("protocol") != protocol:
        raise MappingError(
            f"mapping protocol {data.get('protocol')} does not match --protocol {protocol}")
    return data


def run_modbus(mapping: Dict[str, Any], host: str, port: int) -> None:
    try:
        from pymodbus.datastore import (
            ModbusDeviceContext,
            ModbusSequentialDataBlock,
            ModbusServerContext,
        )
        from pymodbus.server import StartTcpServer
    except ImportError as exc:
        raise SystemExit(
            "pymodbus is required for --protocol modbus: pip install pymodbus") from exc

    devices = {}
    for device in mapping["devices"].values():
        max_hr = 1
        max_co = 1
        for point in device["points"].values():
            if point.get("area") == "hr":
                max_hr = max(max_hr, point["address"] + point["count"])
            elif point.get("area") == "co":
                max_co = max(max_co, point["address"] + point["count"])
        devices[device["unit_id"]] = ModbusDeviceContext(
            hr=ModbusSequentialDataBlock(1, [0] * max_hr),
            co=ModbusSequentialDataBlock(1, [False] * max_co),
        )
    context = ModbusServerContext(devices=devices, single=False)
    print(f"modbus simulator listening on {host}:{port} units={sorted(devices)}")
    StartTcpServer(context=context, address=(host, port))


def run_opcua(mapping: Dict[str, Any], host: str, port: int) -> None:
    try:
        from asyncua import Server, ua
    except ImportError as exc:
        raise SystemExit(
            "asyncua is required for --protocol opcua: pip install asyncua") from exc

    async def serve() -> None:
        server = Server()
        await server.init()
        server.set_endpoint(f"opc.tcp://{host}:{port}")
        idx = await server.register_namespace("http://thing-model.local")
        objects = server.nodes.objects
        for device in mapping["devices"].values():
            folder = await objects.add_folder(idx, device["device_name"])
            for key, point in device["nodes"].items():
                initial = 0.0 if point["type"] in ("float", "double") else (
                    False if point["type"] in ("bool", "boolean") else 0)
                var = await folder.add_variable(
                    ua.NodeId(f"{device['device_name']}.{key}", idx), key, initial)
                await var.set_writable()
        print(f"opcua simulator listening on opc.tcp://{host}:{port}")
        async with server:
            await asyncio.Event().wait()

    asyncio.run(serve())


def run_s7(mapping: Dict[str, Any], host: str, port: int) -> None:
    try:
        from snap7.server import Server
        from snap7.type import SrvArea
    except ImportError as exc:
        raise SystemExit(
            "python-snap7 is required for --protocol s7: pip install python-snap7") from exc

    server = Server()
    for device in mapping["devices"].values():
        server.register_area(SrvArea.DB, device["db_number"], bytearray(1024))
    server.start(tcp_port=port)
    print(f"s7 simulator listening on {host}:{port} dbs={[d['db_number'] for d in mapping['devices'].values()]}")
    try:
        threading.Event().wait()
    except KeyboardInterrupt:
        pass
    finally:
        server.stop()
        server.destroy()


def run_can(mapping: Dict[str, Any], port: int) -> None:
    try:
        import can
    except ImportError as exc:
        raise SystemExit(
            "python-can is required for --protocol can: pip install python-can") from exc

    bus = can.Bus(
        interface=mapping.get("interface", "udp_multicast"),
        channel=mapping.get("channel", "239.255.0.1"),
        port=port,
        fd=bool(mapping.get("fd", False)),
    )
    print(
        f"can monitor interface={mapping.get('interface')} "
        f"channel={mapping.get('channel')} port={port}")
    try:
        while True:
            msg = bus.recv(timeout=1.0)
            if msg is not None:
                print(f"can id=0x{msg.arbitration_id:X} data={msg.data.hex()}")
    except KeyboardInterrupt:
        pass
    finally:
        bus.shutdown()


def ensure_odbc_schema(mapping: Dict[str, Any], host: str, port: int) -> None:
    try:
        import psycopg
    except ImportError as exc:
        raise SystemExit(
            "psycopg is required for --protocol odbc: pip install 'psycopg[binary]'") from exc

    conninfo = (
        f"host={host} port={port} dbname={mapping['database']} "
        f"user={mapping['user']} password={mapping['password']} connect_timeout=5")
    with psycopg.connect(conninfo, autocommit=True) as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS gateway_telemetry (
                    device_name text NOT NULL,
                    product_id text NOT NULL,
                    ts bigint NOT NULL,
                    key text NOT NULL,
                    value_text text,
                    value_double double precision,
                    value_bool boolean
                )
                """
            )
            cur.execute(
                "CREATE INDEX IF NOT EXISTS gateway_telemetry_ts_idx "
                "ON gateway_telemetry (ts)"
            )
            cur.execute("SELECT COUNT(*) FROM gateway_telemetry")
            count = cur.fetchone()[0]
    print(
        f"odbc PostgreSQL ready host={host} port={port} "
        f"database={mapping['database']} rows={count}")


def main() -> int:
    args = parse_args()
    try:
        mapping = load_mapping(args.mapping, args.protocol)
    except Exception as exc:
        print(f"error: {exc}")
        return 1
    port = args.port or int(mapping.get("port") or DEFAULT_PORTS[args.protocol])

    if args.protocol == "modbus":
        run_modbus(mapping, args.host, port)
    elif args.protocol == "opcua":
        run_opcua(mapping, args.host, port)
    elif args.protocol == "s7":
        run_s7(mapping, args.host, port)
    elif args.protocol == "can":
        run_can(mapping, port)
    else:
        ensure_odbc_schema(mapping, "127.0.0.1", port)
        print("odbc schema is ready; start simulate_gateway_all.py --protocol odbc")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
